#!/usr/bin/env python3
"""
Measure distances between converted DBS electrode points and DWI-space tractography.

Inputs are expected in DWI/native RAS coordinates:
  - electrode CSV generated by convert_leaddbs_fcsv_to_ossdbs_points.py
  - MRtrix .tck streamlines or ASCII VTK POLYDATA streamlines

Outputs:
  - per-streamline distances CSV
  - summary JSON
"""

from __future__ import annotations

import argparse
import csv
import json
import struct
from pathlib import Path

import numpy as np


ROOT = Path(r"D:\dbs_workspace")
DEFAULT_ELECTRODES = ROOT / "dbs_stn_hdp_pipeline" / "patients" / "patient_example" / "derivatives" / "lead_dbs" / "sub-PatientExample_electrodefiducials_spaces.csv"
DEFAULT_OUTPUT_PREFIX = ROOT / "dbs_stn_hdp_pipeline" / "patients" / "patient_example" / "derivatives" / "lead_dbs" / "distance_qc" / "sub-PatientExample_electrode_tract_distances"
DEFAULT_TRACTS = [
    (
        "L_CST_official",
        ROOT / "dbs_stn_hdp_pipeline" / "patients" / "patient_example" / "derivatives" / "tracts" / "official" / "L_CST_current_official.tck",
        "E8_E15",
    ),
    (
        "L_DRTT_official",
        ROOT / "dbs_stn_hdp_pipeline" / "patients" / "patient_example" / "derivatives" / "tracts" / "official" / "L_DRTT_iFOD2_strictEndpoint_nodil_to_LPG_official_max160.tck",
        "E8_E15",
    ),
    (
        "L_HDP_official_max80",
        ROOT / "dbs_stn_hdp_pipeline" / "patients" / "patient_example" / "derivatives" / "tracts" / "official" / "L_HDP_refined_official_max80.vtk",
        "E8_E15",
    ),
]


def read_electrodes(path: Path) -> dict[str, np.ndarray]:
    rows = []
    with path.open(newline="") as f:
        for row in csv.DictReader(f):
            rows.append(
                {
                    "label": row["label"],
                    "dwi": np.array(
                        [float(row["dwi_ras_x"]), float(row["dwi_ras_y"]), float(row["dwi_ras_z"])],
                        dtype=float,
                    ),
                }
            )
    rows.sort(key=lambda item: int(item["label"][1:]))
    return {
        "E0_E7": np.vstack([r["dwi"] for r in rows[:8]]),
        "E8_E15": np.vstack([r["dwi"] for r in rows[8:16]]),
    }


def read_tck(path: Path) -> list[np.ndarray]:
    streamlines: list[np.ndarray] = []
    current: list[list[float]] = []
    with path.open("rb") as f:
        header = {}
        while True:
            line = f.readline().decode("latin-1").strip()
            if line == "END":
                break
            if ":" in line:
                key, value = line.split(":", 1)
                header[key.strip()] = value.strip()
        offset = int(header.get("file", ". 0").split()[-1])
        f.seek(offset)
        while True:
            data = f.read(12)
            if len(data) < 12:
                break
            x, y, z = struct.unpack("<fff", data)
            point = np.array([x, y, z], dtype=float)
            if np.isinf(point).any():
                if current:
                    streamlines.append(np.array(current, dtype=float))
                break
            if np.isnan(point).any():
                if current:
                    streamlines.append(np.array(current, dtype=float))
                    current = []
                continue
            current.append([x, y, z])
    return streamlines


def read_vtk_polydata_ascii(path: Path) -> list[np.ndarray]:
    lines = path.read_text().splitlines()
    if len(lines) < 4 or "ASCII" not in lines[:4] or "DATASET POLYDATA" not in lines[:6]:
        raise ValueError(f"Only ASCII VTK POLYDATA is supported: {path}")

    point_idx = next(i for i, line in enumerate(lines) if line.startswith("POINTS "))
    parts = lines[point_idx].split()
    n_points = int(parts[1])
    coords = []
    i = point_idx + 1
    while len(coords) < n_points * 3:
        coords.extend(float(x) for x in lines[i].split())
        i += 1
    points = np.array(coords, dtype=float).reshape(n_points, 3)

    line_idx = next(j for j, line in enumerate(lines) if line.startswith("LINES "))
    line_parts = lines[line_idx].split()
    n_lines = int(line_parts[1])
    values = []
    i = line_idx + 1
    while len(values) < int(line_parts[2]):
        values.extend(int(x) for x in lines[i].split())
        i += 1

    streamlines = []
    cursor = 0
    for _ in range(n_lines):
        count = values[cursor]
        cursor += 1
        indices = values[cursor : cursor + count]
        cursor += count
        streamlines.append(points[indices])
    return streamlines


def read_streamlines(path: Path) -> list[np.ndarray]:
    suffix = path.suffix.lower()
    if suffix == ".tck":
        return read_tck(path)
    if suffix == ".vtk":
        return read_vtk_polydata_ascii(path)
    raise ValueError(f"Unsupported streamline format: {path}")


def fit_axis(points: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    center = points.mean(axis=0)
    _, _, vh = np.linalg.svd(points - center, full_matrices=False)
    direction = vh[0]
    if np.dot(points[-1] - points[0], direction) < 0:
        direction *= -1
    return center, direction / np.linalg.norm(direction)


def point_to_axis_distance(points: np.ndarray, axis_point: np.ndarray, axis_direction: np.ndarray) -> np.ndarray:
    rel = points - axis_point
    projection = np.outer(rel @ axis_direction, axis_direction)
    perpendicular = rel - projection
    return np.linalg.norm(perpendicular, axis=1)


def summarize(values: np.ndarray) -> dict:
    percentiles = np.percentile(values, [0, 5, 25, 50, 75, 95, 100])
    return {
        "n": int(values.size),
        "min_mm": float(percentiles[0]),
        "p05_mm": float(percentiles[1]),
        "p25_mm": float(percentiles[2]),
        "median_mm": float(percentiles[3]),
        "p75_mm": float(percentiles[4]),
        "p95_mm": float(percentiles[5]),
        "max_mm": float(percentiles[6]),
        "mean_mm": float(np.mean(values)),
        "within_1mm": int(np.sum(values <= 1.0)),
        "within_2mm": int(np.sum(values <= 2.0)),
        "within_3mm": int(np.sum(values <= 3.0)),
        "within_5mm": int(np.sum(values <= 5.0)),
    }


def measure_tract(name: str, path: Path, electrode_points: np.ndarray) -> tuple[list[dict], dict]:
    streamlines = read_streamlines(path)
    axis_point, axis_direction = fit_axis(electrode_points)
    contact_center = electrode_points.mean(axis=0)

    rows = []
    nearest_point_distances = []
    axis_distances = []
    contact_distances = []

    for idx, streamline in enumerate(streamlines):
        if streamline.size == 0:
            continue
        d_to_points = np.linalg.norm(streamline[:, None, :] - electrode_points[None, :, :], axis=2)
        min_point = float(np.min(d_to_points))
        min_axis = float(np.min(point_to_axis_distance(streamline, axis_point, axis_direction)))
        min_contact = float(np.min(np.linalg.norm(streamline - contact_center, axis=1)))

        nearest_point_distances.append(min_point)
        axis_distances.append(min_axis)
        contact_distances.append(min_contact)
        rows.append(
            {
                "tract": name,
                "streamline_index": idx,
                "n_points": int(len(streamline)),
                "min_to_any_electrode_point_mm": min_point,
                "min_to_lead_axis_mm": min_axis,
                "min_to_electrode_centroid_mm": min_contact,
            }
        )

    summary = {
        "tract": name,
        "path": str(path),
        "n_streamlines": len(streamlines),
        "electrode_points_first": electrode_points[0].tolist(),
        "electrode_points_last": electrode_points[-1].tolist(),
        "lead_axis_point": axis_point.tolist(),
        "lead_axis_direction": axis_direction.tolist(),
        "electrode_centroid": contact_center.tolist(),
        "min_to_any_electrode_point": summarize(np.array(nearest_point_distances, dtype=float)),
        "min_to_lead_axis": summarize(np.array(axis_distances, dtype=float)),
        "min_to_electrode_centroid": summarize(np.array(contact_distances, dtype=float)),
    }
    return rows, summary


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--electrodes", type=Path, default=DEFAULT_ELECTRODES)
    parser.add_argument("--out-prefix", type=Path, default=DEFAULT_OUTPUT_PREFIX)
    parser.add_argument(
        "--tract",
        action="append",
        nargs=3,
        metavar=("NAME", "PATH", "ELECTRODE_GROUP"),
        help="Tract name, .tck path, electrode group (E0_E7 or E8_E15). Can be repeated.",
    )
    args = parser.parse_args()

    electrodes = read_electrodes(args.electrodes)
    tract_specs = args.tract or [(name, str(path), group) for name, path, group in DEFAULT_TRACTS]

    all_rows: list[dict] = []
    summaries = []
    for name, path_str, group in tract_specs:
        path = Path(path_str)
        rows, summary = measure_tract(name, path, electrodes[group])
        summary["electrode_group"] = group
        summaries.append(summary)
        all_rows.extend(rows)

    csv_path = args.out_prefix.with_suffix(".per_streamline.csv")
    json_path = args.out_prefix.with_suffix(".summary.json")
    write_csv(csv_path, all_rows)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps({"electrodes": str(args.electrodes), "tracts": summaries}, indent=2), encoding="utf-8")

    print(f"Wrote: {csv_path}")
    print(f"Wrote: {json_path}")
    for summary in summaries:
        print(
            f"{summary['tract']} ({summary['electrode_group']}): "
            f"n={summary['n_streamlines']}, "
            f"median point={summary['min_to_any_electrode_point']['median_mm']:.2f} mm, "
            f"median axis={summary['min_to_lead_axis']['median_mm']:.2f} mm, "
            f"within 3 mm point={summary['min_to_any_electrode_point']['within_3mm']}"
        )


if __name__ == "__main__":
    main()
