#!/usr/bin/env python3
"""
Generate full Medtronic SenSight B33005 contact coordinates from DiODe rotation.

Inputs:
  - B33005 axial level centers from export_b33005_axis_level_centers.py.
  - DiODe summary from run_b33005_diode_from_slicer_axis.m.

The DiODe output y point is interpreted the same way Lead-DBS does in
ea_calcxy.m: it defines the lead-local y marker direction around the
K0-to-K3 axis. Segment coordinates follow Lead-DBS B33005 local geometry:
K1A/K2A at +Y, K1B/K2B at -X/-Y, K1C/K2C at +X/-Y.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np


ROOT = Path(r"D:\dbs_workspace")
DEFAULT_LEVELS = (
    ROOT
    / "dbs_stn_hdp_pipeline"
    / "patients"
    / "patient_example"
    / "derivatives"
    / "lead_dbs"
    / "sub-PatientExample_B33005_axis_level_centers.csv"
)
DEFAULT_DIODE = (
    ROOT
    / "dbs_stn_hdp_pipeline"
    / "patients"
    / "patient_example"
    / "derivatives"
    / "lead_dbs"
    / "diode_matlab_qc"
    / "sub-PatientExample_B33005_diode_from_slicer_axis_summary.csv"
)
DEFAULT_T12DWI = (
    ROOT
    / "dbs_stn_hdp_pipeline"
    / "patients"
    / "patient_example"
    / "derivatives"
    / "registration"
    / "t12dwi_mrtrix.txt"
)
DEFAULT_OUT_PREFIX = (
    ROOT
    / "dbs_stn_hdp_pipeline"
    / "patients"
    / "patient_example"
    / "derivatives"
    / "lead_dbs"
    / "sub-PatientExample_B33005_contacts_from_diode"
)

LEAD_DIAMETER_MM = 1.3
RADIUS_MM = LEAD_DIAMETER_MM / 2.0
CX_MM = RADIUS_MM * np.cos(np.pi / 6.0)
CY_MM = RADIUS_MM * np.sin(np.pi / 6.0)

CONTACT_LOCAL_OFFSETS = {
    "K0": ("K0", np.array([0.0, 0.0, 0.0])),
    "K1A": ("K1_level", np.array([0.0, RADIUS_MM, 0.0])),
    "K1B": ("K1_level", np.array([-CX_MM, -CY_MM, 0.0])),
    "K1C": ("K1_level", np.array([CX_MM, -CY_MM, 0.0])),
    "K2A": ("K2_level", np.array([0.0, RADIUS_MM, 0.0])),
    "K2B": ("K2_level", np.array([-CX_MM, -CY_MM, 0.0])),
    "K2C": ("K2_level", np.array([CX_MM, -CY_MM, 0.0])),
    "K3": ("K3", np.array([0.0, 0.0, 0.0])),
}


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def point(row: dict[str, str], prefix: str) -> np.ndarray:
    return np.array(
        [float(row[f"{prefix}_x"]), float(row[f"{prefix}_y"]), float(row[f"{prefix}_z"])],
        dtype=float,
    )


def normalize(vector: np.ndarray, name: str) -> np.ndarray:
    norm = np.linalg.norm(vector)
    if norm == 0 or not np.isfinite(norm):
        raise ValueError(f"Cannot normalize {name}: {vector}")
    return vector / norm


def apply_affine(points: np.ndarray, matrix: np.ndarray) -> np.ndarray:
    return (matrix @ np.c_[points, np.ones(len(points))].T).T[:, :3]


def lead_dbs_calcxy(head: np.ndarray, tail: np.ndarray, y_marker_vector: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Replicate helpers/ea_calcxy.m for numeric y input."""
    zunit = normalize(tail - head, "lead axis")
    y_marker_unit = normalize(y_marker_vector, "DiODe y marker vector")
    x = np.cross(y_marker_unit, np.array([0.0, 0.0, 1.0]))
    x = x - np.dot(x, zunit) * zunit
    xunit = normalize(x, "projected x axis")
    yunit = -np.cross(xunit, zunit)
    yunit = normalize(yunit, "computed y axis")
    return xunit, yunit


def levels_by_lead(rows: list[dict[str, str]]) -> dict[str, dict[str, dict[str, str]]]:
    out: dict[str, dict[str, dict[str, str]]] = {}
    for row in rows:
        lead = row["lead"]
        level = row["level_name"].split()[0]
        out.setdefault(lead, {})[level] = row
    return out


def diode_by_lead(rows: list[dict[str, str]]) -> dict[str, dict[str, str]]:
    return {row["side_name"]: row for row in rows}


def build_contacts(level_rows: list[dict[str, str]], diode_rows: list[dict[str, str]], t12dwi: Path) -> tuple[list[dict], dict]:
    levels = levels_by_lead(level_rows)
    diode = diode_by_lead(diode_rows)

    anchor_to_dwi = np.linalg.inv(np.loadtxt(t12dwi))
    rows: list[dict] = []
    qc = {
        "method": "Lead-DBS B33005 local segment geometry rotated by DiODe y marker direction.",
        "inputs": {
            "levels_csv": str(DEFAULT_LEVELS),
            "diode_summary_csv": str(DEFAULT_DIODE),
            "t12dwi_mrtrix": str(t12dwi),
        },
        "coordinate_conventions": {
            "anchorNative": "Slicer/Lead-DBS RAS mm",
            "dwi": "RAS mm, generated by applying inverse MRtrix t12dwi matrix to anchorNative contact points",
        },
        "b33005_geometry_mm": {
            "lead_diameter": LEAD_DIAMETER_MM,
            "radius": RADIUS_MM,
            "cx": CX_MM,
            "cy": CY_MM,
        },
        "leads": {},
    }

    for lead_name, side_letter in [("right", "R"), ("left", "L")]:
        lead_levels = levels[lead_name]
        diode_row = diode[lead_name]
        head = point(lead_levels["K0"], "anchorNative_ras")
        tail = point(lead_levels["K3"], "anchorNative_ras")
        y_point = np.array(
            [float(diode_row["y_x"]), float(diode_row["y_y"]), float(diode_row["y_z"])],
            dtype=float,
        )
        xunit, yunit = lead_dbs_calcxy(head, tail, y_point - head)
        zunit = normalize(tail - head, "K0-to-K3 axis")

        lead_contacts_anchor = {}
        for contact_name, (level_name, local_offset) in CONTACT_LOCAL_OFFSETS.items():
            center = point(lead_levels[level_name], "anchorNative_ras")
            anchor = center + local_offset[0] * xunit + local_offset[1] * yunit
            dwi = apply_affine(anchor.reshape(1, 3), anchor_to_dwi)[0]
            full_name = f"{side_letter}_{contact_name}"
            lead_contacts_anchor[full_name] = anchor
            rows.append(
                {
                    "contact_name": full_name,
                    "lead": lead_name,
                    "side": side_letter,
                    "electrode_model": "Medtronic B33005",
                    "diode_roll_y_deg": float(diode_row["roll_y_deg"]),
                    "source_level": level_name,
                    "local_x_mm": local_offset[0],
                    "local_y_mm": local_offset[1],
                    "local_z_mm": local_offset[2],
                    "anchorNative_ras_x": anchor[0],
                    "anchorNative_ras_y": anchor[1],
                    "anchorNative_ras_z": anchor[2],
                    "dwi_ras_x": dwi[0],
                    "dwi_ras_y": dwi[1],
                    "dwi_ras_z": dwi[2],
                }
            )

        qc["leads"][lead_name] = {
            "side": side_letter,
            "roll_y_deg": float(diode_row["roll_y_deg"]),
            "head_k0_anchorNative_ras": head.tolist(),
            "tail_k3_anchorNative_ras": tail.tolist(),
            "diode_y_point_anchorNative_ras": y_point.tolist(),
            "xunit_anchorNative": xunit.tolist(),
            "yunit_anchorNative": yunit.tolist(),
            "zunit_anchorNative": zunit.tolist(),
            "orthogonality_checks": {
                "dot_x_y": float(np.dot(xunit, yunit)),
                "dot_x_z": float(np.dot(xunit, zunit)),
                "dot_y_z": float(np.dot(yunit, zunit)),
            },
            "segment_centroid_distances_to_axis_mm": {
                name: float(np.linalg.norm(point - point_on_axis(point, head, zunit)))
                for name, point in lead_contacts_anchor.items()
            },
        }

    return rows, qc


def point_on_axis(point_: np.ndarray, axis_point: np.ndarray, axis_unit: np.ndarray) -> np.ndarray:
    return axis_point + np.dot(point_ - axis_point, axis_unit) * axis_unit


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_fcsv(path: Path, rows: list[dict], prefix: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as f:
        f.write("# Markups fiducial file version = 5.6\n")
        f.write("# CoordinateSystem = RAS\n")
        f.write("# columns = id,x,y,z,ow,ox,oy,oz,vis,sel,lock,label,desc,associatedNodeID\n")
        for idx, row in enumerate(rows):
            label = row["contact_name"]
            f.write(
                f"vtkMRMLMarkupsFiducialNode_{idx},"
                f"{row[f'{prefix}_x']},{row[f'{prefix}_y']},{row[f'{prefix}_z']},"
                f"0,0,0,1,1,1,0,{label},DiODe B33005 contact center,\n"
            )


def write_vtk(path: Path, rows: list[dict], prefix: str) -> None:
    points = []
    point_index = {}
    for row in rows:
        point_index[row["contact_name"]] = len(points)
        points.append(np.array([row[f"{prefix}_x"], row[f"{prefix}_y"], row[f"{prefix}_z"]], dtype=float))

    lines = []
    for side in ["R", "L"]:
        lines.append([point_index[f"{side}_K0"], point_index[f"{side}_K3"]])
        lines.extend(
            [
                [point_index[f"{side}_K1A"], point_index[f"{side}_K1B"]],
                [point_index[f"{side}_K1B"], point_index[f"{side}_K1C"]],
                [point_index[f"{side}_K1C"], point_index[f"{side}_K1A"]],
                [point_index[f"{side}_K2A"], point_index[f"{side}_K2B"]],
                [point_index[f"{side}_K2B"], point_index[f"{side}_K2C"]],
                [point_index[f"{side}_K2C"], point_index[f"{side}_K2A"]],
            ]
        )

    with path.open("w") as f:
        f.write("# vtk DataFile Version 3.0\n")
        f.write("B33005 DiODe contact centers and segment triangles\n")
        f.write("ASCII\n")
        f.write("DATASET POLYDATA\n")
        f.write(f"POINTS {len(points)} float\n")
        for p in points:
            f.write(f"{p[0]} {p[1]} {p[2]}\n")
        f.write(f"VERTICES {len(points)} {len(points) * 2}\n")
        for idx in range(len(points)):
            f.write(f"1 {idx}\n")
        f.write(f"LINES {len(lines)} {sum(len(line) + 1 for line in lines)}\n")
        for line in lines:
            f.write(f"{len(line)} {' '.join(str(i) for i in line)}\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--levels", type=Path, default=DEFAULT_LEVELS)
    parser.add_argument("--diode-summary", type=Path, default=DEFAULT_DIODE)
    parser.add_argument("--t12dwi-mrtrix", type=Path, default=DEFAULT_T12DWI)
    parser.add_argument("--out-prefix", type=Path, default=DEFAULT_OUT_PREFIX)
    args = parser.parse_args()

    level_rows = read_csv(args.levels)
    diode_rows = read_csv(args.diode_summary)
    rows, qc = build_contacts(level_rows, diode_rows, args.t12dwi_mrtrix)
    qc["inputs"]["levels_csv"] = str(args.levels)
    qc["inputs"]["diode_summary_csv"] = str(args.diode_summary)

    csv_path = args.out_prefix.with_suffix(".csv")
    json_path = args.out_prefix.with_suffix(".qc.json")
    anchor_fcsv_path = args.out_prefix.with_suffix(".anchorNative.fcsv")
    dwi_fcsv_path = args.out_prefix.with_suffix(".dwi.fcsv")
    anchor_vtk_path = args.out_prefix.with_suffix(".anchorNative.vtk")
    dwi_vtk_path = args.out_prefix.with_suffix(".dwi.vtk")

    write_csv(csv_path, rows)
    json_path.write_text(json.dumps(qc, indent=2), encoding="utf-8")
    write_fcsv(anchor_fcsv_path, rows, "anchorNative_ras")
    write_fcsv(dwi_fcsv_path, rows, "dwi_ras")
    write_vtk(anchor_vtk_path, rows, "anchorNative_ras")
    write_vtk(dwi_vtk_path, rows, "dwi_ras")

    for path in [csv_path, json_path, anchor_fcsv_path, dwi_fcsv_path, anchor_vtk_path, dwi_vtk_path]:
        print(f"Wrote: {path}")
    for lead_name, lead_qc in qc["leads"].items():
        print(
            f"{lead_name}: roll_y={lead_qc['roll_y_deg']:.1f} deg, "
            f"dot(x,y/z)={lead_qc['orthogonality_checks']['dot_x_y']:.2e}/"
            f"{lead_qc['orthogonality_checks']['dot_x_z']:.2e}"
        )


if __name__ == "__main__":
    main()
